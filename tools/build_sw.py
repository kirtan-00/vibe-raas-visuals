#!/usr/bin/env python3
"""Regenerate sw.js (the offline service worker) from the files git tracks.
Run from anywhere:  python3 tools/build_sw.py   then commit sw.js.
Skips raas/ (unlisted), shots/ (untracked) and tools/. Adds every CDN script the pages use."""
import hashlib, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP = ('raas/', 'tools/', '.')
files = subprocess.run(['git', 'ls-files'], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
files = sorted(f for f in files if not f.startswith(SKIP) and '/shots/' not in f and f != 'sw.js')
dirs = sorted({f.split('/')[0] + '/' for f in files if f.endswith('/index.html')})
cdn = set()
for f in files:
    if f.endswith(('.html', '.js')):
        cdn.update(re.findall(r'https://cdn\.jsdelivr\.net/npm/[^"\'\s)]+', open(os.path.join(ROOT, f), encoding='utf-8').read()))
urls = ['./'] + dirs + files + sorted(cdn)
h = hashlib.sha256()
for f in files:
    h.update(f.encode()); h.update(open(os.path.join(ROOT, f), 'rb').read())
for u in sorted(cdn): h.update(u.encode())
version = 'vr-' + h.hexdigest()[:10]

sw = """/* Vibe Raas offline service worker. GENERATED by tools/build_sw.py: do not edit by hand, rerun the script.
   Online: pages and scripts come from the network first (so updates show up), with the cache as fallback.
   Offline: everything comes from the precache. Fonts, images and CDN libraries are cache-first. */
'use strict';
const VERSION = %s;
const PRECACHE = %s;
const NET_TIMEOUT = 2500; // venue wifi with no upstream must not hang a visual switch

self.addEventListener('install', e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(PRECACHE.map(u => new Request(u, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('vr-') && k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
function bare(u) { const x = new URL(u); x.search = ''; x.hash = ''; return x.href; }
function fromCache(req) { return caches.match(req, { ignoreSearch: true }); }
async function networkFirst(req) {
  if (self.navigator && self.navigator.onLine === false) { const c = await fromCache(req); if (c) return c; }
  try {
    const res = await Promise.race([fetch(req), new Promise((_, rej) => setTimeout(() => rej(new Error('slow')), NET_TIMEOUT))]);
    if (res && res.ok) { const copy = res.clone(); caches.open(VERSION).then(c => c.put(bare(req.url), copy)).catch(() => {}); }
    return res;
  } catch (err) {
    const c = await fromCache(req);
    if (c) return c;
    throw err;
  }
}
async function cacheFirst(req) {
  const c = await fromCache(req);
  if (c) return c;
  const res = await fetch(req);
  if (res && (res.ok || res.type === 'opaque')) { const copy = res.clone(); caches.open(VERSION).then(c2 => c2.put(req, copy)).catch(() => {}); }
  return res;
}
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const u = new URL(req.url);
  const same = u.origin === self.location.origin;
  if (!same && u.hostname !== 'cdn.jsdelivr.net') return; // MQTT websockets etc are not ours to touch
  const code = same && (req.mode === 'navigate' || req.destination === 'iframe' || req.destination === 'document' || /(\\/|\\.html|\\.js)$/.test(u.pathname));
  e.respondWith(code ? networkFirst(req) : cacheFirst(req));
});
self.addEventListener('message', e => {
  if (!e.data || e.data.type !== 'check' || !e.ports[0]) return;
  const port = e.ports[0];
  Promise.all(PRECACHE.map(u => caches.match(new URL(u, self.registration.scope).href, { ignoreSearch: true }).then(r => !!r)))
    .then(rs => { const n = rs.filter(Boolean).length; port.postMessage({ ok: n === PRECACHE.length, cached: n, total: PRECACHE.length, version: VERSION }); })
    .catch(() => port.postMessage({ ok: false, cached: 0, total: PRECACHE.length }));
});
""" % (json.dumps(version), json.dumps(urls, indent=1))
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw)
print(version, len(urls), 'urls')
